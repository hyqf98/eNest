import assert from 'node:assert/strict'
import test from 'node:test'
import { DatabaseSync } from 'node:sqlite'
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../../../', import.meta.url))
const result = await build({ entryPoints: [root+'src/main/database/tableOperations.ts'], tsconfig: root+'tsconfig.node.json', bundle:true,write:false,platform:'node',format:'esm' })
const api = await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'))

test('table browsing parameterizes values, validates columns and uses primary keys for stable pages',()=>{
  const query=api.buildBrowseQuery('postgres',{table:{schema:'public',table:'people'},limit:20,offset:40,filters:[{column:'name',operator:'eq',value:"'; DROP TABLE people; --"}],order:[{column:'name',direction:'desc'}]},['id','name'],['id'])
  assert.equal(query.sql,'SELECT * FROM "public"."people" WHERE "name" = $1 ORDER BY "name" DESC, "id" ASC LIMIT 21 OFFSET 40')
  assert.deepEqual(query.params,["'; DROP TABLE people; --"])
  assert.equal(query.stableOrder,true)
  assert.throws(()=>api.buildBrowseQuery('mysql',{table:{table:'people'},order:[{column:'secret',direction:'asc'}]},['id']),/Unknown column/)
  assert.throws(()=>api.buildBrowseQuery('sqlite',{table:{table:'people'},offset:-1},[]),/offset/)
  assert.throws(()=>api.buildBrowseQuery('sqlite',{table:{table:'people'},filters:[{column:'id',operator:'in',value:[]}]},['id']),/IN requires/)
  assert.equal(api.tableOperationsFlavor('redis'),undefined)
})

test('SQLite generated DDL, foreign keys, indexes and server-side filtering work on a real engine',()=>{
  const db=new DatabaseSync(':memory:')
  try {
    db.exec('PRAGMA foreign_keys=ON; CREATE TABLE departments(id INTEGER PRIMARY KEY); INSERT INTO departments VALUES(1)')
    const table={schema:'main',table:'people'}
    const created=api.previewTableDesign('sqlite',{operation:'create-table',table,columns:[
      {name:'id',type:'integer',autoIncrement:true},
      {name:'name',type:'varchar',nullable:false,default:{kind:'literal',value:"O'Brien"}},
      {name:'department',type:'integer'}
    ],primaryKey:['id'],foreignKeys:[{columns:['department'],references:{schema:'main',table:'departments'},referencedColumns:['id']}]})
    db.exec(created.sql)
    db.exec("INSERT INTO people (department) VALUES (1); INSERT INTO people(name,department) VALUES ('100%_safe',1),('other',1)")
    assert.throws(()=>db.exec("INSERT INTO people(department) VALUES(5)"),/FOREIGN KEY/)
    const query=api.buildBrowseQuery('sqlite',{table,limit:1,filters:[{column:'name',operator:'contains',value:'%_'}]},['id','name','department'],['id'])
    const rows=db.prepare(query.sql).all(...query.params)
    assert.equal(rows.length,1)
    assert.equal(rows[0].name,'100%_safe')
    const page=api.buildBrowseQuery('sqlite',{table,limit:1,offset:1},['id','name','department'],['id'])
    assert.deepEqual(db.prepare(page.sql).all(...page.params).map(row=>row.id),[2,3])
    for(const design of [
      {operation:'create-index',name:'people_name',columns:['name'],unique:true},
      {operation:'drop-index',name:'people_name'},
      {operation:'add-column',column:{name:'note',type:'text'}},
      {operation:'rename-column',column:'note',newName:'memo'},
      {operation:'drop-column',column:'memo'}
    ]) db.exec(api.previewTableDesign('sqlite',{table,...design}).sql)
    assert.equal(db.prepare('SELECT name FROM people WHERE id=1').get().name,"O'Brien")
  } finally {db.close()}
})

test('DDL identifies destructive actions and rejects conflicting or malformed designs',()=>{
  assert.equal(api.previewTableDesign('mysql',{operation:'drop-column',table:{database:'prod',table:'events'},column:'old'}).destructive,true)
  const pg=api.previewTableDesign('postgres',{operation:'create-table',table:{schema:'app',table:'events'},columns:[{name:'id',type:'bigint',autoIncrement:true},{name:'payload',type:'json'}],primaryKey:['id']})
  assert.match(pg.sql,/BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL/)
  assert.match(pg.sql,/JSONB/)
  assert.throws(()=>api.previewTableDesign('sqlite',{operation:'create-table',table:{table:'bad'},columns:[{name:'id',type:'bigint',autoIncrement:true}],primaryKey:['id']}),/INTEGER primary/)
  assert.throws(()=>api.previewTableDesign('postgres',{operation:'create-table',table:{table:'bad'},columns:[{name:'id',type:'integer'},{name:'id',type:'text'}]}),/Duplicate/)
  assert.throws(()=>api.previewTableDesign('mysql',{operation:'add-column',table:{table:'x'},column:{name:'x',type:'integer',default:{kind:'expression',value:'1; DROP TABLE x'}}}),/Unsupported default/)
  assert.equal(api.previewTableDesign('mysql',{operation:'add-column',table:{table:'x` y'},column:{name:'a',type:'varchar',default:{kind:'literal',value:"a\\b'"}}}).sql,"ALTER TABLE `x`` y` ADD COLUMN `a` VARCHAR(255) DEFAULT X'615c6227';")
})
